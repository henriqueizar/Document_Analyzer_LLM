#!/usr/bin/env bash
# Installs and starts the application on this machine (production mode, Docker).
#
#   cd deploy && ./install.sh
#
# Asks three questions (address, where the LLM runs, which model), generates
# every secret, builds the images, downloads the model and starts everything.
# The answers can also come from the environment, for unattended installs:
#   DOLLMA_ADDRESS=docs.empresa.local DOLLMA_LLM=gpu|cpu|native DOLLMA_MODEL=qwen3:8b ./install.sh
# DOLLMA_SKIP_BUILD=1 uses images already loaded with `docker load` (for
# servers without internet: build them elsewhere, see docs/implantacao.md).
#
# Internet is used only here (Docker images, npm packages, the model). After
# that the application runs without it.
set -euo pipefail
cd "$(dirname "$0")"

say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
fail() { printf '\nErro: %s\n' "$*" >&2; exit 1; }
ask() { # ask <variable> <question> <default>
  local current="${!1:-}"
  if [ -n "$current" ]; then return; fi
  if [ ! -t 0 ]; then printf -v "$1" '%s' "$3"; return; fi
  local answer
  read -r -p "$2 [$3]: " answer
  printf -v "$1" '%s' "${answer:-$3}"
}
resolves() { # can this machine find the address? (IP, localhost, DNS or /etc/hosts)
  local name="$1"
  [ "$name" = localhost ] && return 0
  [[ "$name" =~ ^[0-9]+(\.[0-9]+){3}$ ]] && return 0
  if command -v getent >/dev/null 2>&1; then getent hosts "$name" >/dev/null 2>&1 && return 0; fi
  if command -v dscacheutil >/dev/null 2>&1; then dscacheutil -q host -a name "$name" | grep -q ip_address && return 0; fi
  return 1
}
secret() { # 48 hex characters: safe in URLs and .env files
  if command -v openssl >/dev/null 2>&1; then openssl rand -hex 24
  else od -An -tx1 -N24 /dev/urandom | tr -d ' \n'; fi
}

command -v docker >/dev/null 2>&1 || fail "o Docker não está instalado (https://docs.docker.com/get-docker/)."
docker compose version >/dev/null 2>&1 || fail "o Docker Compose v2 não está disponível ('docker compose')."
docker info >/dev/null 2>&1 || fail "o Docker não está rodando. Inicie o Docker e rode de novo."

if [ -f .env ]; then
  say "Já instalado (deploy/.env existe). Subindo com a configuração atual..."
  if [ "${DOLLMA_SKIP_BUILD:-0}" = 1 ]; then docker compose up -d; else docker compose up -d --build; fi
  say "Pronto. Para mudar endereço ou modelo, edite deploy/.env e rode: docker compose up -d"
  sleep 5
  code=$(docker compose logs backend 2>/dev/null | grep -o 'Setup code[^:]*: [A-Z0-9-]*' | tail -1 | awk '{print $NF}')
  [ -n "$code" ] && echo "Administrador ainda não criado. Código de instalação: $code"
  exit 0
fi

say "Instalação do Document LLM Analyzer"
echo
echo "Endereço de acesso: o que as pessoas vão digitar no navegador para abrir o app."
echo "  - Só nesta máquina: localhost"
echo "  - Na rede da empresa: o nome do servidor na rede (ex.: documentos.empresa.local)"
echo "    ou o IP dele (ex.: 192.168.0.20). Não é um nome para a instalação: precisa existir na rede."
while true; do
  ask DOLLMA_ADDRESS "Endereço de acesso" "localhost"
  candidate="${DOLLMA_ADDRESS#https://}"; candidate="${candidate#http://}"; candidate="${candidate%%/*}"; candidate="${candidate%%:*}"
  if resolves "$candidate"; then break; fi
  echo "Aviso: \"$candidate\" não foi encontrado nesta máquina (nenhum DNS ou /etc/hosts o conhece)."
  echo "Os navegadores também não vão encontrá-lo, e o HTTPS só vale para este endereço."
  if [ ! -t 0 ]; then fail "endereço não encontrado: $candidate"; fi
  read -r -p "Usar mesmo assim? (s/N): " keep
  case "$keep" in s|S|sim|SIM) break ;; esac
  DOLLMA_ADDRESS=""
done
echo
echo "Onde a LLM (Ollama) vai rodar?"
echo "  gpu    - no Docker, com GPU NVIDIA (servidor Linux; recomendado para empresas)"
echo "  cpu    - no Docker, só com CPU (funciona em qualquer máquina, mas é lento)"
echo "  native - no app do Ollama instalado nesta máquina (recomendado no Mac: usa a GPU da Apple)"
default_llm=cpu
[ "$(uname -s)" = "Darwin" ] && default_llm=native
ask DOLLMA_LLM "Opção" "$default_llm"
ask DOLLMA_MODEL "Modelo" "qwen3:8b"

case "$DOLLMA_LLM" in
  gpu) files="docker-compose.yml:docker-compose.gpu.yml"; profiles="ollama" ;;
  cpu) files="docker-compose.yml"; profiles="ollama" ;;
  native) files="docker-compose.yml:docker-compose.native-ollama.yml"; profiles="" ;;
  *) fail "opção de LLM inválida: $DOLLMA_LLM (use gpu, cpu ou native)." ;;
esac

address="${DOLLMA_ADDRESS#https://}"
address="${address%/}"
if [[ "$address" == http://* ]]; then
  site_address="$address"; site_url="$address"   # plain HTTP, if explicitly asked for
else
  site_address="$address"; site_url="https://$address"
fi

say "Gerando a configuração (deploy/.env, legível só por você)..."
umask 077
cat > .env <<ENV
# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%MZ). Keep it secret: it holds
# the passwords and keys of this installation. Back it up together with the data.
COMPOSE_FILE=$files
COMPOSE_PROFILES=$profiles
SITE_ADDRESS=$site_address
SITE_URL=$site_url
LLM_MODEL=$DOLLMA_MODEL
POSTGRES_PASSWORD=$(secret)
BACKEND_JWT_SECRET=$(secret)
NEXTAUTH_SECRET=$(secret)
BACKUP_UID=$(id -u):$(id -g)
ENV
umask 022
mkdir -p backups

if [ "${DOLLMA_SKIP_BUILD:-0}" = 1 ]; then
  # Images built elsewhere and loaded with `docker load` (servers without internet).
  say "Usando as imagens já carregadas (DOLLMA_SKIP_BUILD=1)."
else
  say "Montando as imagens (a primeira vez leva alguns minutos)..."
  docker compose build
fi

if [ "$DOLLMA_LLM" = "native" ]; then
  if command -v ollama >/dev/null 2>&1; then
    say "Baixando o modelo $DOLLMA_MODEL no Ollama desta máquina..."
    ollama pull "$DOLLMA_MODEL"
  else
    echo "Aviso: o comando 'ollama' não foi encontrado. Instale o Ollama (https://ollama.com),"
    echo "abra o app e rode: ollama pull $DOLLMA_MODEL"
  fi
else
  # The LLM container has no internet once running, so the model is downloaded
  # now by a temporary container that shares its storage.
  say "Baixando o modelo $DOLLMA_MODEL (alguns GB)..."
  docker compose up --no-start >/dev/null 2>&1   # creates the volumes, owned by Compose
  docker run --rm --entrypoint sh -v dollma_ollama:/root/.ollama ollama/ollama:latest \
    -c 'ollama serve >/dev/null 2>&1 & for i in $(seq 1 30); do ollama list >/dev/null 2>&1 && break; sleep 1; done; ollama pull "$0"' \
    "$DOLLMA_MODEL"
fi

say "Iniciando..."
docker compose up -d

printf 'Aguardando o sistema responder'
for _ in $(seq 1 90); do
  if docker compose exec -T backend node -e "fetch('http://localhost:3000/health').then(r=>process.exit(r.ok?0:1),()=>process.exit(1))" >/dev/null 2>&1; then
    ok=1; break
  fi
  printf '.'; sleep 2
done
echo
[ "${ok:-0}" = 1 ] || fail "o backend não respondeu. Veja: docker compose logs backend"

if [[ "$site_url" == https://* ]]; then
  # The local certificate authority is created on the first HTTPS request.
  curl -sk -o /dev/null "https://localhost:${HTTPS_PORT:-443}" -H "Host: $site_address" || true
  sleep 2
  docker compose cp proxy:/data/caddy/pki/authorities/local/root.crt ./dollma-root.crt >/dev/null 2>&1 && chmod 644 dollma-root.crt || true
fi

code=$(docker compose logs backend 2>/dev/null | grep -o 'Setup code[^:]*: [A-Z0-9-]*' | tail -1 | awk '{print $NF}')
say "Instalado. Acesse: $site_url"
echo "Na primeira visita, crie a conta de administrador com o código de instalação:"
echo
printf '    \033[1m%s\033[0m\n' "${code:-(veja: docker compose logs backend | grep 'Setup code')}"
echo
echo "Só quem tem acesso a este servidor vê esse código: ninguém mais consegue criar o administrador."
if [ -f dollma-root.crt ]; then
  echo
  echo "Certificado: o HTTPS usa uma autoridade certificadora local, criada nesta máquina."
  echo "Para os navegadores não mostrarem aviso, instale deploy/dollma-root.crt como"
  echo "certificado raiz confiável nas máquinas que vão acessar (veja docs/implantacao.md)."
fi
echo
echo "Backups automáticos: todo dia, em deploy/backups/ (últimos 14 dias). Copie essa pasta para outro disco."
echo "Esqueceu a senha do administrador? ./reset-password.sh <e-mail>"
echo "Comandos úteis (nesta pasta): docker compose ps | docker compose logs -f | ./backup.sh | ./update.sh"
